import { spawnSync } from 'node:child_process';
import { chmodSync, mkdtempSync, writeFileSync } from 'node:fs';
import { tmpdir } from 'node:os';
import { join } from 'node:path';
import { fileURLToPath } from 'node:url';
import { describe, expect, it } from 'vitest';

// The repo-root PreToolUse guard (.claude/hooks/guard-live-executor.mjs) that blocks real-spend
// commands in Claude Code sessions. Exit 2 blocks the Bash call; exit 0 lets it through.
const GUARD = fileURLToPath(new URL('../../../.claude/hooks/guard-live-executor.mjs', import.meta.url));

// Scripts the guard reads when a command runs them.
const DIR = mkdtempSync(join(tmpdir(), 'guard-'));
writeFileSync(join(DIR, 'safe.sh'), '#!/bin/sh\nnpm test\n');
writeFileSync(join(DIR, 'live.sh'), '#!/bin/sh\necho start\nnpm run runner\n');
writeFileSync(join(DIR, 'envs.sh'), '#!/usr/bin/env -S bash -e\nnpm run runner\n');
writeFileSync(join(DIR, 'envq.sh'), "#!/usr/bin/env -S 'bash' -e\nnpm run runner\n");
writeFileSync(join(DIR, 'live.mjs'), "require('node:child_process').execFileSync('npm', ['run', 'runner']);\n");
writeFileSync(join(DIR, 'runner-docs.mjs'), "console.log('docs');\n");
writeFileSync(join(DIR, 'live.py'), "import subprocess\nsubprocess.run(['npm', 'run', 'runner'])\n");
writeFileSync(join(DIR, 'livemod.py'), "import subprocess\nsubprocess.run(['npm', 'run', 'runner'])\n");
writeFileSync(join(DIR, 'live.cjs'), "require('node:child_process').execFileSync('npm', ['run', 'runner']);\n");
writeFileSync(join(DIR, 'tool.py'), "print('hello')\n");
writeFileSync(join(DIR, 'tool.mjs'), '#!/usr/bin/env node\nconsole.log("npm run runner");\n');
for (const f of ['safe.sh', 'live.sh', 'envs.sh', 'envq.sh', 'tool.mjs']) chmodSync(join(DIR, f), 0o755);

function guard(command: string): number | null {
  const r = spawnSync(process.execPath, [GUARD], { input: JSON.stringify({ tool_input: { command }, cwd: DIR }) });
  return r.status;
}

